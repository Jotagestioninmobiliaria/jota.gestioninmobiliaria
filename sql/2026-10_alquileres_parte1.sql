-- ---------- ajustes ICL (historial de cada aumento) ----------
create table if not exists ajustes_icl (
  id               bigint generated by default as identity primary key,
  alquiler_id      bigint not null references alquileres(id),
  periodo          text   not null,           -- 'MM-AAAA', igual que pagos_mensuales
  fecha_base       date   not null,           -- inicio del período anterior
  fecha_ajuste     date   not null,           -- día en que rige el aumento
  icl_fecha_base   date,                      -- fecha del valor ICL usado (puede ser el día hábil previo)
  icl_fecha_ajuste date,
  icl_inicial      numeric not null,
  icl_final        numeric not null,
  coeficiente      numeric not null,
  importe_anterior numeric not null,
  importe_nuevo    numeric not null,
  provisorio       boolean default false,     -- true si el ICL del día del ajuste todavía no estaba publicado
  confirmado_at    timestamptz default now(),
  unique (alquiler_id, periodo)
);

