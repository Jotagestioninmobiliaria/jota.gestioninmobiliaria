-- Servicios que se controlan en cada unidad, ej. 'TGI,AGUAS,EXPENSAS'
-- (vacío = los que tienen número de cuenta cargado)
alter table alquileres add column if not exists servicios text;

-- Control mes a mes de cada impuesto/servicio
create table if not exists servicios_mes (
  id              bigint generated by default as identity primary key,
  alquiler_id     bigint not null references alquileres(id),
  periodo         text   not null,          -- 'MM-AAAA'
  servicio        text   not null,          -- TGI, AGUAS, EPE, GAS, API, EXPENSAS
  boleta_enviada  boolean default false,    -- MAO le mandó la boleta al inquilino
  pagado          boolean default false,    -- llegó el comprobante (en API: lo pagó MAO)
  no_corresponde  boolean default false,    -- ese mes no hay boleta
  monto           numeric,                  -- API pagada por MAO (se descuenta al propietario)
  extraordinarias numeric,                  -- expensas extraordinarias (se descuentan del alquiler)
  notas           text,
  updated_at      timestamptz default now(),
  unique (alquiler_id, periodo, servicio)
);

-- API pagada por adelantado hasta un mes ('MM-AAAA'), ej. '12-2026' = todo el año
alter table alquileres add column if not exists api_pagada_hasta text;
