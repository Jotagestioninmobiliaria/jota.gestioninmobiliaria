-- Interés por mora de cada unidad: 0.05 = 5% por mes de atraso (vacío = sin interés)
alter table alquileres add column if not exists interes_mensual numeric;

-- Intereses ya calculados/pagados de cada mes adeudado (para no cobrarlos dos veces)
alter table pagos_mensuales add column if not exists interes_devengado    numeric;
alter table pagos_mensuales add column if not exists interes_calc_periodo text;
alter table pagos_mensuales add column if not exists interes_pagado       numeric;

-- Deudas cargadas a mano (lo anterior a noviembre 2026, expensas, etc.)
create table if not exists deudas (
  id                   bigint generated by default as identity primary key,
  alquiler_id          bigint not null references alquileres(id),
  inquilino            text,                    -- quién la debe (por si después cambia el inquilino)
  periodo              text   not null,         -- 'MM-AAAA' del mes adeudado
  concepto             text   not null default 'Alquiler',  -- Alquiler, Expensas, Cochera, Intereses, Otro
  detalle              text,
  monto                numeric not null,        -- lo que quedó pendiente
  pagado               numeric not null default 0,
  moneda               text default 'ARS',
  interes_devengado    numeric,
  interes_calc_periodo text,
  interes_pagado       numeric,
  created_at           timestamptz default now()
);

-- Historial de pagos recibidos y a qué meses se aplicó cada uno
create table if not exists cobros (
  id          bigint generated by default as identity primary key,
  alquiler_id bigint not null references alquileres(id),
  fecha       date   not null,
  monto       numeric not null,
  periodo     text,                -- mes que se estaba mirando al registrarlo
  detalle     jsonb,               -- a qué deuda/mes fue cada parte (y cómo estaba antes, para poder anularlo)
  created_at  timestamptz default now()
);
